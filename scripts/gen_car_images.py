#!/usr/bin/env python3
"""
Builds every car image used by the game from the AI-generated *_raw.png files:
  1. keys out the flat blue background (ImageMagick flood fill),
  2. creates colour variants for the dealership catalogue,
  3. encodes them as WebP and embeds them as base64 data URLs in
     src/assets/cars/images.ts (a text module, so no binary build artefacts are needed).
Run:  python3 scripts/gen_car_images.py
"""
import base64, os, shutil, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CARS = os.path.join(ROOT, "src", "assets", "cars")
OUT = os.path.join(CARS, "images.ts")
TMP = "/tmp/car-img"
SIZE = 760

BASES = {
    "comet": "comet_raw.png",
    "thunder": "thunder_raw.png",
    "phantom": "phantom_raw.png",
    "interceptor": "police_raw.png",
}

# id -> (base id, extra ImageMagick operators). modulate hue: 100 = 0deg, +1 = +1.8deg
VARIANTS = {
    "comet-rs": ("comet", ["-modulate", "100,108,183"]),
    "comet-gt": ("comet", ["-modulate", "102,115,11"]),
    "comet-evo": ("comet", ["-modulate", "100,100,56"]),
    "thunder-rx": ("thunder", ["-modulate", "100,95,153"]),
    "thunder-ss": ("thunder", ["-modulate", "100,100,5"]),
    "thunder-hc": ("thunder", ["-modulate", "95,112,83"]),
    "phantom-r": ("phantom", ["-modulate", "100,100,33"]),
    "phantom-x": ("phantom", ["-modulate", "100,100,167"]),
    "phantom-sv": ("phantom", ["-modulate", "100,108,139"]),
    "interceptor-gold": ("interceptor", ["-colorspace", "Gray", "-colorspace", "sRGB",
                                         "-channel", "RGB", "+level-colors", "#241505,#ffe27a", "+channel"]),
}


def sh(*args):
    return subprocess.run(list(args), check=True, capture_output=True, text=True).stdout.strip()


def key_out(raw, dst):
    w = int(sh("identify", "-format", "%w", raw))
    h = int(sh("identify", "-format", "%h", raw))
    bg = sh("convert", raw, "-format", "%[pixel:p{4,4}]", "info:")
    cmd = ["convert", raw, "-alpha", "set", "-fuzz", "11%", "-transparent", bg,
           "-channel", "RGBA", "-fuzz", "16%", "-fill", "none"]
    for x, y in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1),
                 (w // 2, 0), (w // 2, h - 1), (0, h // 2), (w - 1, h // 2)]:
        cmd += ["-draw", f"matte {x},{y} floodfill"]
    cmd += ["+channel", "-channel", "A", "-morphology", "Erode", "Diamond:1",
            "-blur", "0x0.6", "+channel", "-trim", "+repage",
            "-resize", f"{SIZE}x{SIZE}", "-strip", f"PNG32:{dst}"]
    subprocess.run(cmd, check=True)


def main():
    os.makedirs(TMP, exist_ok=True)
    pngs = {}
    for cid, raw in BASES.items():
        dst = os.path.join(TMP, f"{cid}.png")
        key_out(os.path.join(CARS, raw), dst)
        pngs[cid] = dst
    for cid, (base, ops) in VARIANTS.items():
        dst = os.path.join(TMP, f"{cid}.png")
        subprocess.run(["convert", pngs[base], *ops, f"PNG32:{dst}"], check=True)
        pngs[cid] = dst

    use_webp = shutil.which("cwebp") is not None
    lines = ["// AUTO-GENERATED by scripts/gen_car_images.py - do not edit by hand.", "",
             "export const CAR_IMG: Record<string, string> = {"]
    dims, total = [], 0
    for cid, png in pngs.items():
        w = int(sh("identify", "-format", "%w", png))
        h = int(sh("identify", "-format", "%h", png))
        if use_webp:
            out = png[:-4] + ".webp"
            subprocess.run(["cwebp", "-quiet", "-q", "82", "-alpha_q", "90", "-m", "6", png, "-o", out], check=True)
            mime = "image/webp"
        else:
            out, mime = png, "image/png"
        data = open(out, "rb").read()
        total += len(data)
        lines.append(f'  "{cid}": "data:{mime};base64,{base64.b64encode(data).decode()}",')
        dims.append(f'  "{cid}": [{w}, {h}],')
        print(f"{cid:18s} {w}x{h}  {len(data) // 1024} KB")
    lines += ["};", "", "export const CAR_DIM: Record<string, [number, number]> = {", *dims, "};"]
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({'webp' if use_webp else 'png'}, {total // 1024} KB binary)")


if __name__ == "__main__":
    main()
